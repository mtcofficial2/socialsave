/// Newest use stays first. Duplicates are dropped. The list stops at 32.
List<String> rememberEmoji(List<String> recent, String emoji) {
  final clean = emoji.trim();
  if (clean.isEmpty) return List<String>.of(recent);
  final next = <String>[clean, for (final item in recent) if (item != clean) item];
  if (next.length > 32) return next.sublist(0, 32);
  return next;
}

/// Adds [emoji] when it is missing, and removes it when it is already kept.
List<String> toggleFavorite(List<String> favorites, String emoji) {
  final clean = emoji.trim();
  if (clean.isEmpty) return List<String>.of(favorites);
  if (favorites.contains(clean)) {
    return [for (final item in favorites) if (item != clean) item];
  }
  return [clean, ...favorites];
}

